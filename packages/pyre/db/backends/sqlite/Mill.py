# my superclass
from ..standard import Mill as standard

# the local exceptions
from ... import exceptions

# the type declarators of my columns
from .Columns import Columns

# and the literals of their values
from .Literals import Literals


# declaration
class Mill(standard.Mill, family="pyre.db.dialects.sqlite"):
    """
    Generate SQL statements in the dialect of sqlite: standard SQL, except where sqlite departs
    from it
    """

    # the name of my language, for the explanations of refusals
    dialect = "sqlite"
    # the words that make a creation conditional on the absence of what it creates
    ifMissing = "IF NOT EXISTS"
    # and a removal conditional on the presence of what it removes
    ifPresent = "IF EXISTS"
    # sqlite has indexes
    hasIndexes = True

    # the visitor that builds the type declarators of my columns
    columns = Columns
    # and the one that renders the literals of their values
    literals = Literals

    # transactions
    def transaction(self):
        """
        Generate the SQL statement that initiates a transaction block
        """
        # every statement starts at the margin
        self.margin()
        # sqlite begins its transactions its own way
        yield self.place("BEGIN TRANSACTION;")
        # all done
        return

    # implementation details
    def _default(self, table, column):
        """
        Build the declaration of the default of {column} of {table}, if it has one
        """
        # sqlite assigns the values only of the column that is the whole primary key of its
        # table, the id of the row; such a column is a primary key of its own
        alone = column._primary and not table._pyre_primaryKeys
        # or the only field of the primary key of the table
        only = tuple(table._pyre_primaryKeys) == (column,)
        # a column whose values the server assigns
        if column._autogenerated:
            # must be one of them
            if not (alone or only):
                # or sqlite cannot assign its values
                raise exceptions.NotSupportedError(
                    diagnostic=(
                        f"the column {table.pyre_name}.{column.name} is not the whole primary key"
                        f" of its table, so {self.dialect} cannot assign its values"
                    ),
                    table=table.pyre_name,
                    column=column.name,
                )
            # and declares nothing, since being the id of the row is the whole of it
            return ""
        # the others are declared as standard SQL declares them
        return super()._default(table=table, column=column)

    def _insertColumns(self, table, record):
        """
        Generate the columns of {table} that {record} names in an insert, with their values
        """
        # sqlite has no {DEFAULT} among the values of an insert
        for field, value in zip(table.pyre_fields, record):
            # so the columns left to their defaults, and those whose values the server assigns
            # that have none
            if value is table.default or (field._autogenerated and value is None):
                # are left out
                continue
            # and the others are named
            yield field, value
        # all done
        return


