"""
Check that the file of statements a backup server writes when it reproduces a sqlite database for
postgres runs on postgres, and leaves the tables with their rows and their keys
"""


def test():
    """
    Reproduce a table of sqlite as a file of statements, run the file on postgres, and check the
    rows and the key of a new one
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="pyre_reproduce_file"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # the source, a sqlite database in memory
    source = pyre.db.sqlite(name="reproduce_file_source").attach()
    # with the table
    source.createTable(Granule)
    # and three granules, whose keys sqlite assigns
    source.insert(*(Granule.pyre_immutable(name=name) for name in "abc"))
    # the file of statements, named after this driver and kept for inspection
    path = "reproduce_file.sql"
    # written for postgres
    backup = pyre.db.backup(
        name="reproduce_file_backup",
        stream=path,
        sql=pyre.db.backends.postgres.mill(name="reproduce_file_mill"),
    )
    # by reproducing the table
    backup.reproduce(source=source, tables=(Granule,))
    # make sure the file is on disk
    backup.stream.close()
    # read it
    with open(path) as stream:
        # all of it
        statements = stream.read()
    # the target
    target = pyre.db.postgres(name="reproduce_file").attach()
    # carefully
    try:
        # run the file
        target.execute(statements)
        # the rows that are there, with their keys
        rows = sorted((row.id, row.name) for row in target.select(query=Granule))
        # are the ones of the source
        assert rows == [(1, "a"), (2, "b"), (3, "c")], rows
        # add a granule
        (added,) = target.insert(Granule.pyre_immutable(name="d"), returning=Granule.id)
        # whose key follows the largest
        assert added.id == 4, added.id
    # either way
    finally:
        # leave nothing behind
        target.dropTable(Granule, missingOk=True)
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


