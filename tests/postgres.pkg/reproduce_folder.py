"""
Check that a postgres server reproduces the tables of a folder, with their rows of every type and
the keys another server assigned, and goes on after the largest key
"""


def test():
    """
    Reproduce a sqlite table into a folder, then the folder into postgres, and compare the rows
    """
    # externals
    import datetime
    import decimal
    import shutil

    # access the package
    import pyre.db

    # a table of readings
    class Reading(pyre.db.table, id="pyre_reproduce_folder"):
        """
        Readings
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # a label
        label = pyre.db.str()
        # whether it is good
        good = pyre.db.bool()
        # a measurement
        size = pyre.db.float()
        # a price
        cost = pyre.db.decimal(precision=7, scale=2)
        # a day
        day = pyre.db.date()
        # a moment
        moment = pyre.db.timestamp()
        # and some octets
        blob = pyre.db.bytes()

    # the source, a sqlite database in memory
    source = pyre.db.sqlite(name="reproduce_folder_source").attach()
    # with the table
    source.createTable(Reading)
    # and two readings, whose keys sqlite assigns
    source.insert(
        Reading.pyre_immutable(
            label="a\tb",
            good=True,
            size=1.5,
            cost=decimal.Decimal("2.50"),
            day=datetime.date(2026, 11, 24),
            moment=datetime.datetime(2026, 11, 24, 1, 2, 3),
            blob=b"\x00\xff",
        ),
        Reading.pyre_immutable(label=None, good=False),
    )

    # the folder, named after this driver and kept for inspection
    folder = "reproduce_folder"
    # starts out missing
    shutil.rmtree(folder, ignore_errors=True)
    # reproduce the table into it
    pyre.db.folder(name="reproduce_folder_writer", path=folder).attach().reproduce(
        source=source, tables=(Reading,)
    )
    # the target
    target = pyre.db.postgres(name="reproduce_folder").attach()
    # carefully
    try:
        # reproduce the table from the folder
        target.reproduce(
            source=pyre.db.folder(name="reproduce_folder_reader", path=folder).attach(),
            tables=(Reading,),
        )
        # the rows of the source
        expected = [tuple(row) for row in source.select(query=Reading)]
        # and those of the target
        reproduced = sorted(tuple(row) for row in target.select(query=Reading))
        # are the same
        assert reproduced == expected, reproduced
        # and a new reading gets the key after the largest
        (added,) = target.insert(Reading.pyre_immutable(label="c"), returning=Reading.id)
        # which is three
        assert added.id == 3, added.id
    # either way
    finally:
        # leave nothing behind
        target.dropTable(Reading, missingOk=True)
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


