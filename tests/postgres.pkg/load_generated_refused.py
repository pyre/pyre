"""
Check that a load refuses the value of a column whose values the server assigns, unless it is
asked to keep the values it is given, before anything reaches the table
"""


def test():
    """
    Load granules that bring their own keys into a table whose keys postgres assigns
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="pyre_load_generated_refused"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # connect
    db = pyre.db.postgres(name="load_generated_refused").attach()
    # make the table
    db.createTable(Granule)
    # carefully
    try:
        # the granules, with their keys
        granules = [
            Granule.pyre_immutable(id=index, name=name) for index, name in enumerate("ab", start=1)
        ]
        # whether the load was refused
        refused = False
        # carefully
        try:
            # load them
            db.load(*granules)
        # the refusal
        except pyre.db.exceptions.InterfaceError as error:
            # names the column
            assert "pyre_load_generated_refused.id" in str(error), str(error)
            # and is what is expected
            refused = True
        # make sure it happened
        assert refused
        # and that nothing reached the table
        assert list(db.select(query=Granule)) == []
    # either way
    finally:
        # leave nothing behind
        db.dropTable(Granule)
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


