"""
Check that postgres hands back the keys it assigns to the rows an insert adds
"""


def test():
    """
    Insert two granules without their keys, and read back the keys postgres gave them
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="pyre_returning"):
        """
        Granules
        """

        # the key
        id = pyre.db.int(bits=64).autogenerated().primary()
        # and the name
        name = pyre.db.str()

    # connect
    db = pyre.db.postgres(name="returning").attach()
    # in a transaction that leaves nothing behind
    db.execute("BEGIN")
    # carefully
    try:
        # make the table
        db.createTable(Granule)
        # insert two granules, asking for the keys the server gave them
        rows = db.insert(
            Granule.pyre_immutable(name="first"),
            Granule.pyre_immutable(name="second"),
            returning=Granule.id,
        )
        # the rows read as records of the returned field
        keys = [row.id for row in rows]
        # which the server numbered
        assert keys == [1, 2], keys
    # either way
    finally:
        # leave nothing behind
        db.execute("ROLLBACK")
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


