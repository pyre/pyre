"""
Check that a table postgres reproduces assigns the keys of new rows after the largest key it was
given
"""


def test():
    """
    Reproduce a table of granules, insert another, and check the key postgres assigns it
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="pyre_reproduce_identity"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # the source, a sqlite database in memory
    source = pyre.db.sqlite(name="reproduce_identity_source").attach()
    # with the table
    source.createTable(Granule)
    # and three granules, whose keys sqlite assigns
    source.insert(*(Granule.pyre_immutable(name=name) for name in "abc"))
    # the target
    target = pyre.db.postgres(name="reproduce_identity").attach()
    # carefully
    try:
        # reproduce the table
        target.reproduce(source=source, tables=(Granule,))
        # add a granule
        (added,) = target.insert(Granule.pyre_immutable(name="d"), returning=Granule.id)
        # whose key follows the largest
        assert added.id == 4, added.id
    # either way
    finally:
        # leave nothing behind
        target.dropTable(Granule, missingOk=True)
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


