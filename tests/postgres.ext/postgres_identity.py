"""
Check that postgres assigns the values of an identity column
"""


def test():
    """
    Insert two granules without their keys, and read the keys postgres assigned
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="pyre_identity"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()
        # the name
        name = pyre.db.str()

    # connect
    db = pyre.db.postgres(name="identity").attach()
    # in a transaction that leaves nothing behind
    db.execute("BEGIN")
    # carefully
    try:
        # make the table
        db.createTable(Granule)
        # insert two granules, without their keys
        db.insert(Granule.pyre_immutable(name="first"), Granule.pyre_immutable(name="second"))
        # read them back
        rows = sorted((row.id, row.name) for row in db.select(Granule))
        # postgres numbered them
        assert rows == [(1, "first"), (2, "second")], rows
    # either way
    finally:
        # leave nothing behind
        db.execute("ROLLBACK")
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


