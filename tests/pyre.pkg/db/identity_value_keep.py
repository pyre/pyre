"""
Check that an insert asked to keep the values of the columns the server assigns writes them, and
tells postgres to take them over its own
"""


def test():
    """
    Insert a record with its key, keeping it, and check the statement
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.postgres.mill(name="identities")
    # build the statement
    statement = tuple(
        mill.insertRecords(Granule.pyre_immutable(id=7, name="first"), generated="keep")
    )
    # and check it
    assert statement == (
        "INSERT INTO granules",
        "    (id, name)",
        "  OVERRIDING SYSTEM VALUE",
        "  VALUES",
        "    (7, 'first');",
    ), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


