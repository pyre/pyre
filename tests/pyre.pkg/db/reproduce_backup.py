"""
Check that a backup server reproduces a table as a file of statements in the dialect of its mill:
the table in a transaction, its rows with their keys, then its indexes, then the restart of its
keys after the largest
"""


def test():
    """
    Reproduce a table of sqlite as a file of statements for postgres, and check the statements
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # indexed by name
    Granule.pyre_index(Granule.name)

    # the source, a database in memory
    source = pyre.db.sqlite(name="reproduce_backup_source").attach()
    # with the table
    source.createTable(Granule)
    # and two granules, whose keys sqlite assigns
    source.insert(Granule.pyre_immutable(name="a"), Granule.pyre_immutable(name="b"))
    # the target, a file of statements for postgres, named after this driver
    target = pyre.db.backup(
        name="reproduce_backup",
        stream="reproduce_backup.sql",
        sql=pyre.db.backends.postgres.mill(name="reproduce_backup_mill"),
    )
    # reproduce the table
    target.reproduce(source=source, tables=(Granule,))
    # make sure the file is on disk
    target.stream.close()
    # read it
    with open("reproduce_backup.sql") as stream:
        # all of it
        statements = stream.read()
    # the landmarks of the reproduction, in the order they must appear
    landmarks = (
        "START TRANSACTION",
        "CREATE TABLE granules",
        "OVERRIDING SYSTEM VALUE",
        "(1, 'a')",
        "(2, 'b')",
        "CREATE INDEX",
        "ALTER TABLE granules ALTER COLUMN id RESTART WITH 3;",
        "COMMIT",
    )
    # find them
    places = [statements.find(landmark) for landmark in landmarks]
    # each one is there
    assert all(place >= 0 for place in places), (places, statements)
    # in order
    assert places == sorted(places), (places, statements)
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


