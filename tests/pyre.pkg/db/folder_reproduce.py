"""
Check that a database reproduced into a folder, and from the folder into another database, keeps
its rows and the keys its server assigned, and that the second database goes on after them
"""


def test():
    """
    Reproduce a sqlite database into a folder, then the folder into another sqlite database
    """
    # externals
    import shutil

    # access the package
    import pyre.db

    # a table of missions
    class Mission(pyre.db.table, id="missions"):
        """
        Missions
        """

        # the name
        name = pyre.db.str().primary()

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()
        # and the mission
        mission = pyre.db.str().references(key=Mission.name)

    # the source, a database in memory
    source = pyre.db.sqlite(name="folder_reproduce_source").attach()
    # with the table of missions
    source.createTable(Mission)
    # and the one of granules
    source.createTable(Granule)
    # a mission
    source.insert(Mission.pyre_immutable(name="nisar"))
    # and three of its granules, whose keys sqlite assigns
    source.insert(*(Granule.pyre_immutable(name=name, mission="nisar") for name in "abc"))
    # one of which goes away, so the keys have a gap
    source.delete(table=Granule, condition=Granule.name == "b")

    # the folder, named after this driver and kept for inspection
    folder = "folder_reproduce"
    # starts out missing
    shutil.rmtree(folder, ignore_errors=True)
    # reproduce the tables into it
    pyre.db.folder(name="folder_reproduce", path=folder).attach().reproduce(
        source=source, tables=(Granule, Mission)
    )
    # another database in memory
    target = pyre.db.sqlite(name="folder_reproduce_target").attach()
    # reproduces them from the folder
    target.reproduce(
        source=pyre.db.folder(name="folder_reproduce_reader", path=folder).attach(),
        tables=(Granule, Mission),
    )
    # the granules it holds, with their keys
    granules = sorted((row.id, row.name, row.mission) for row in target.select(query=Granule))
    # are the ones of the source
    assert granules == [(1, "a", "nisar"), (3, "c", "nisar")], granules
    # add a granule
    (added,) = target.insert(
        Granule.pyre_immutable(name="d", mission="nisar"), returning=Granule.id
    )
    # whose key follows the largest
    assert added.id == 4, added.id
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


