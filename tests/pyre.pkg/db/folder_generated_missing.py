"""
Check that a folder server refuses a record that leaves a value to the server, since a folder
assigns none, and that it writes the default of a column for a record that asks for it
"""


def test():
    """
    Load a granule without its key into a folder, then one that asks for the default of its size
    """
    # externals
    import shutil

    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which a server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()
        # and the size
        size = pyre.db.int(default=7)

    # the folder, named after this driver and kept for inspection
    folder = "folder_generated_missing"
    # starts out missing
    shutil.rmtree(folder, ignore_errors=True)
    # attach a server to it
    db = pyre.db.folder(name="folder_generated_missing", path=folder).attach()
    # make the table
    db.createTable(Granule)
    # carefully
    try:
        # load a granule without its key
        db.load(Granule.pyre_immutable(name="a"))
    # it must be refused
    except pyre.db.exceptions.NotSupportedError as error:
        # naming the column
        assert "granules.id" in str(error), str(error)
    # if it is not
    else:
        # say so
        assert False, "a folder took a record without a value it cannot assign"
    # load one with its key, that asks for the default of its size
    db.load(Granule.pyre_immutable(id=1, name="b", size=Granule.default), generated="keep")
    # its size is the default
    assert [(row.id, row.size) for row in db.select(query=Granule)] == [(1, 7)]
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


