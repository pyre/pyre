"""
Check that sqlite's insert of a record that gives no values returns its row when asked
"""


def test():
    """
    Insert a record that leaves every column to the server, asking for its key, and check the
    statement
    """
    # access the package
    import pyre.db

    # a table whose only column the server fills
    class Tick(pyre.db.table, id="ticks"):
        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()

    # make a mill that speaks the dialect of sqlite, which names no column for such a record
    mill = pyre.db.backends.sqlite.mill(name="returning")
    # build the statement
    statement = tuple(mill.insertRecords(Tick.pyre_immutable(), returning=Tick))
    # and check that it asks for the row
    assert statement == ("INSERT INTO ticks DEFAULT VALUES RETURNING id;",), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


