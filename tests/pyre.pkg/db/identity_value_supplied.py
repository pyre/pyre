"""
Check that an insert writes the value a row brings for a column whose values the server assigns
unless a row supplies one, without being asked to keep it
"""


def test():
    """
    Insert a record with its key into a table that takes supplied keys, and check the statement
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns unless a row supplies one
        id = pyre.db.int(bits=64).autogenerated(supplied=True).primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.postgres.mill(name="identities")
    # build the statement
    statement = tuple(mill.insertRecords(Granule.pyre_immutable(id=7, name="first")))
    # and check it
    assert statement == (
        "INSERT INTO granules",
        "    (id, name)",
        "  VALUES",
        "    (7, 'first');",
    ), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


