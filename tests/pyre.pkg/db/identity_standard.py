"""
Check that standard SQL declares a column whose values the server always assigns
"""


def test():
    """
    Declare an identity column, and check the statement that creates its table
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.standard.mill(name="identities")
    # build the statement
    statement = tuple(mill.createTable(table=Granule))
    # and check it
    assert statement == (
        "CREATE TABLE granules",
        "  --",
        "  -- Granules",
        "  --",
        "(",
        "  id BIGINT GENERATED ALWAYS AS IDENTITY",
        "    PRIMARY KEY,",
        "  name CLOB",
        ");",
    ), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


