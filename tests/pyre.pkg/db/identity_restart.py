"""
Check the statement standard SQL and postgres build to restart the values of a column the server
assigns
"""


def test():
    """
    Ask the standard and the postgres mills for the restart of an identity, and check it
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # the statement each one builds
    for mill in (
        pyre.db.backends.standard.mill(name="standard"),
        pyre.db.backends.postgres.mill(name="postgres"),
    ):
        # build it
        statement = tuple(mill.restartIdentity(table=Granule, field=Granule.id.field, start=8))
        # and check it
        assert statement == ("ALTER TABLE granules ALTER COLUMN id RESTART WITH 8;",), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


