"""
Check that an insert refuses a value for a column whose values the server assigns, unless it is
asked to keep the values it is given
"""


def test():
    """
    Insert a record with its key into a table whose key the server assigns
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.postgres.mill(name="identities")
    # carefully
    try:
        # build the statement of a record that brings its own key
        tuple(mill.insertRecords(Granule.pyre_immutable(id=7, name="first")))
    # it must be refused
    except pyre.db.exceptions.InterfaceError as error:
        # naming the column
        assert "granules.id" in str(error), str(error)
    # if it is not
    else:
        # say so
        assert False, "a value for a column the server assigns was accepted"
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


