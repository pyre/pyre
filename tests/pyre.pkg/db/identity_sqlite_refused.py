"""
Check that sqlite refuses an identity column that is not the primary key
"""


def test():
    """
    Declare an identity column that is not the primary key, and check sqlite refuses it
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated()
        # the name
        name = pyre.db.str()

    # and its exceptions
    from pyre.db import exceptions

    # make a mill that speaks the dialect of sqlite
    mill = pyre.db.backends.sqlite.mill(name="identities")
    # attempt to
    try:
        # build the statement that creates the table
        statement = tuple(mill.createTable(table=Granule))
    # which must fail
    except exceptions.NotSupportedError as error:
        # naming the column
        assert error.column == "id", error.column
        # and the reason
        assert "primary key" in str(error), str(error)
    # if it doesn't
    else:
        # the column was declared anyway
        assert False, statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


