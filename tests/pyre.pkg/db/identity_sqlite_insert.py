"""
Check that sqlite leaves an identity column without a value out of an insert
"""


def test():
    """
    Insert a record without its key, and check the statement the dialect of sqlite builds
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.sqlite.mill(name="identities")
    # build the statement
    statement = tuple(mill.insertRecords(Granule.pyre_immutable(name="first")))
    # and check it
    assert statement == (
        "INSERT INTO granules",
        "    (name)",
        "  VALUES",
        "    ('first');",
    ), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


