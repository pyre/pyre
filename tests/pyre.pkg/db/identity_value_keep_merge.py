"""
Check that a merge asked to keep the values of the columns the server assigns tells the insert of
the rows that are not there to take them over its own
"""


def test():
    """
    Merge a record with its key, keeping both the key and the row that is there, and check the
    statement
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.standard.mill(name="identities")
    # build the statement
    statement = tuple(
        mill.insertRecords(
            Granule.pyre_immutable(id=7, name="first"), existing="keep", generated="keep"
        )
    )
    # and check it
    assert statement == (
        "MERGE INTO granules",
        "  USING (",
        "    VALUES",
        "      (7, 'first')",
        "  ) AS incoming (id, name)",
        "  ON (granules.id = incoming.id)",
        "  WHEN NOT MATCHED THEN INSERT (id, name)",
        "    OVERRIDING SYSTEM VALUE",
        "    VALUES (incoming.id, incoming.name);",
    ), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


