"""
Check that sqlite builds no statement to restart the ids of the rows of a table, since its next id
follows the largest there is
"""


def test():
    """
    Ask the sqlite mill for the restart of an identity, and check that there is none
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # make a mill
    mill = pyre.db.backends.sqlite.mill(name="identities")
    # build the statement
    statement = tuple(mill.restartIdentity(table=Granule, field=Granule.id.field, start=8))
    # and check that there is none
    assert statement == (), statement
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


