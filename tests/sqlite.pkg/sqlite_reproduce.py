"""
Check that a sqlite server reproduces the tables of another database with their rows and the keys
the other server assigned, a few rows at a time
"""


def test():
    """
    Reproduce a table of five granules, two rows at a time, and compare the rows
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int().autogenerated().primary()
        # the name
        name = pyre.db.str()

    # the source, a database in memory
    source = pyre.db.sqlite(name="reproduce_source").attach()
    # with the table
    source.createTable(Granule)
    # and five granules, whose keys sqlite assigns
    source.insert(*(Granule.pyre_immutable(name=name) for name in "abcde"))
    # one of which goes away, so the keys have a gap
    source.delete(table=Granule, condition=Granule.name == "c")
    # the target, another database in memory, that loads two rows at a time
    target = pyre.db.sqlite(name="reproduce_target", batch=2).attach()
    # reproduce the table
    target.reproduce(source=source, tables=(Granule,))
    # the rows of the source, with their keys
    expected = sorted((row.id, row.name) for row in source.select(query=Granule))
    # and those of the target
    reproduced = sorted((row.id, row.name) for row in target.select(query=Granule))
    # are the same
    assert reproduced == expected == [(1, "a"), (2, "b"), (4, "d"), (5, "e")], reproduced
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


