"""
Check that sqlite hands back the keys it assigns to the rows an insert adds
"""


def test():
    """
    Insert two granules without their keys, and read back the keys sqlite gave them
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        # the key
        id = pyre.db.int(bits=64).autogenerated().primary()
        # and the name
        name = pyre.db.str()

    # connect to a database in memory
    db = pyre.db.sqlite(name="returning").attach()
    # make the table
    db.createTable(Granule)
    # insert two granules, asking for the keys the server gave them
    rows = db.insert(
        Granule.pyre_immutable(name="first"),
        Granule.pyre_immutable(name="second"),
        returning=Granule.id,
    )
    # the rows read as records of the returned field
    keys = [row.id for row in rows]
    # which the server numbered
    assert keys == [1, 2], keys
    # disconnect
    db.detach()
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


