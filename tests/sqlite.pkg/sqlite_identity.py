"""
Check that sqlite assigns the values of an identity column
"""


def test():
    """
    Insert two granules without their keys, and read the keys sqlite assigned
    """
    # access the package
    import pyre.db

    # a table of granules
    class Granule(pyre.db.table, id="granules"):
        """
        Granules
        """

        # the key, which the server assigns
        id = pyre.db.int(bits=64).autogenerated().primary()
        # the name
        name = pyre.db.str()

    # connect to a database in memory
    db = pyre.db.sqlite(name="identity").attach()
    # make the table
    db.createTable(Granule)
    # insert two granules, without their keys
    db.insert(Granule.pyre_immutable(name="first"), Granule.pyre_immutable(name="second"))
    # read them back
    rows = sorted((row.id, row.name) for row in db.select(Granule))
    # sqlite numbered them
    assert rows == [(1, "first"), (2, "second")], rows
    # disconnect
    db.detach()
    # all done
    return


# main
if __name__ == "__main__":
    # run the test
    test()


